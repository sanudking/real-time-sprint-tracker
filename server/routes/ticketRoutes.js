const router = require('express').Router();
const auth = require('../middleware/authMiddleware');
const { requireWorkspaceMember } = require('../middleware/roleMiddleware');
const c = require('../controllers/ticketController');
router.use(auth);
router.post('/', c.create);
router.get('/workspace/:workspaceId', requireWorkspaceMember, c.listByWorkspace);
router.get('/workspace/:workspaceId/export', requireWorkspaceMember, c.exportCsv);
router.post('/bulk', c.bulk);
router.get('/:id/activity', c.listActivity);
router.post('/:id/subtasks', c.addSubtask);
router.patch('/:id/subtasks/:subtaskId', c.updateSubtask);
router.delete('/:id/subtasks/:subtaskId', c.removeSubtask);
router.patch('/:id/archive', c.archive);
router.patch('/:id', c.update);
router.patch('/:id/status', c.updateStatus);
router.delete('/:id', c.remove);
module.exports = router;
